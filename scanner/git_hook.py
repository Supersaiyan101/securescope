"""
Git Pre-Commit Hook Manager.

Installs and uninstalls SecureScope as a Git pre-commit hook to automatically
screen staged changes (--diff) for secrets, vulnerabilities, and insecure
dependencies before commits are finalized.
"""

import os
import stat
import subprocess
import sys
from pathlib import Path
from typing import Optional


def find_git_root(target_path: str) -> Optional[str]:
    """Find the root directory of the git repository containing target_path."""
    try:
        result = subprocess.run(
            ["git", "rev-parse", "--show-toplevel"],
            cwd=target_path,
            capture_output=True,
            text=True,
            check=True,
        )
        return result.stdout.strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        pass

    # Fallback directory climbing
    current = Path(target_path).resolve()
    while current != current.parent:
        if (current / ".git").is_dir():
            return str(current)
        current = current.parent
    return None


def get_hook_script_template(cli_path: str, python_exe: Optional[str] = None, fail_severity: str = "high") -> str:
    """Generate the pre-commit shell script content."""
    # Normalize path to forward slashes for cross-platform POSIX sh compatibility
    normalized_cli_path = cli_path.replace("\\", "/")
    normalized_py_exe = (python_exe or sys.executable).replace("\\", "/")

    return f"""#!/bin/sh
# -----------------------------------------------------------------------------
# SecureScope automated Git pre-commit security hook
# Generated by: securescope --install-hook
# -----------------------------------------------------------------------------

echo "🔐 [SecureScope] Auditing staged code and dependencies before commit..."

# Locate python executable
if [ -f "{normalized_py_exe}" ]; then
    PY_CMD="{normalized_py_exe}"
elif command -v py >/dev/null 2>&1; then
    PY_CMD="py"
elif command -v python3 >/dev/null 2>&1; then
    PY_CMD="python3"
elif command -v python >/dev/null 2>&1; then
    PY_CMD="python"
else
    echo "⚠️  [SecureScope] Python executable not found in PATH; skipping pre-commit audit."
    exit 0
fi

# Locate SecureScope CLI entry point
REPO_ROOT=$(git rev-parse --show-toplevel 2>/dev/null || pwd)
if [ -f "$REPO_ROOT/cli.py" ]; then
    CLI_TARGET="$REPO_ROOT/cli.py"
elif [ -f "{normalized_cli_path}" ]; then
    CLI_TARGET="{normalized_cli_path}"
else
    echo "⚠️  [SecureScope] CLI script not found; skipping pre-commit audit."
    exit 0
fi

# Run SecureScope on staged changes in diff mode
"$PY_CMD" "$CLI_TARGET" --diff --fail-on {fail_severity} --skip-ai --output terminal

STATUS=$?
if [ $STATUS -ne 0 ]; then
    echo ""
    echo "🚨 [SecureScope] Commit rejected: Security issues detected in staged changes!"
    echo "   • Run 'python cli.py --diff' to view full findings."
    echo "   • Run 'python cli.py --fix' to automatically apply remediations."
    echo "   • (To force commit in an emergency, use 'git commit --no-verify')"
    echo ""
    exit 1
fi

echo "✅ [SecureScope] Pre-commit security check passed cleanly."
exit 0
"""


def install_pre_commit_hook(target_path: str, fail_severity: str = "high") -> tuple[bool, str]:
    """
    Install SecureScope as a .git/hooks/pre-commit hook.

    Returns:
        (success: bool, message: str)
    """
    git_root = find_git_root(target_path)
    if not git_root:
        return False, f"Target directory is not a Git repository: {target_path}"

    hooks_dir = os.path.join(git_root, ".git", "hooks")
    os.makedirs(hooks_dir, exist_ok=True)

    hook_file = os.path.join(hooks_dir, "pre-commit")

    # Safety backup if non-SecureScope hook already exists
    if os.path.isfile(hook_file):
        try:
            with open(hook_file, "r", encoding="utf-8", errors="ignore") as f:
                content = f.read()
            if "SecureScope" not in content:
                backup_file = hook_file + ".securescope.bak"
                with open(backup_file, "w", encoding="utf-8") as bf:
                    bf.write(content)
        except Exception:
            pass

    # Determine absolute path to cli.py
    cli_path = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "cli.py"))

    script_content = get_hook_script_template(cli_path, fail_severity=fail_severity)

    try:
        with open(hook_file, "w", encoding="utf-8", newline="\n") as f:
            f.write(script_content)

        # Make file executable on Unix/Linux/macOS
        st = os.stat(hook_file)
        os.chmod(hook_file, st.st_mode | stat.S_IEXEC | stat.S_IXGRP | stat.S_IXOTH)

        return True, f"Successfully installed pre-commit hook at: {hook_file}"
    except Exception as e:
        return False, f"Failed to write pre-commit hook: {str(e)}"


def uninstall_pre_commit_hook(target_path: str) -> tuple[bool, str]:
    """
    Remove SecureScope pre-commit hook and restore backup if present.

    Returns:
        (success: bool, message: str)
    """
    git_root = find_git_root(target_path)
    if not git_root:
        return False, f"Target directory is not a Git repository: {target_path}"

    hook_file = os.path.join(git_root, ".git", "hooks", "pre-commit")
    backup_file = hook_file + ".securescope.bak"

    if not os.path.isfile(hook_file):
        return True, "No pre-commit hook found to uninstall."

    try:
        os.remove(hook_file)
        # Restore backup if available
        if os.path.isfile(backup_file):
            os.rename(backup_file, hook_file)
            return True, "Uninstalled SecureScope hook and restored previous pre-commit hook."
        return True, "Successfully uninstalled SecureScope pre-commit hook."
    except Exception as e:
        return False, f"Failed to uninstall pre-commit hook: {str(e)}"
